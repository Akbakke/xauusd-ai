def _bars(n: int, *, seed: int) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    close = 2000.0 + np.cumsum(rng.normal(0.0, 1.5, size=n))
    high = close + np.abs(rng.normal(0.0, 1.0, size=n))
    low = close - np.abs(rng.normal(0.0, 1.0, size=n))
    open_ = np.concatenate([[close[0]], close[:-1]])
    index = pd.date_range("2021-01-04", periods=n, freq="5min", tz="UTC")
    return pd.DataFrame(
        {
            "open": open_,
            "high": np.maximum.reduce([high, open_, close]),
            "low": np.minimum.reduce([low, open_, close]),
            "close": close,
            "volume": rng.integers(400, 601, size=n, dtype=np.int64),
        },
        index=index,
    )


def test_rsi_uses_classic_wilder_seed_and_recursion() -> None:
    # Wilder's canonical worksheet series: the first 14-period RSI and the
    # next recursive observations are independent reference values, not
    # values generated by the implementation under test.
    close = pd.Series(
        [
            44.34, 44.09, 44.15, 43.61, 44.33, 44.83, 45.10, 45.42,
            45.84, 46.08, 45.89, 46.03, 45.61, 46.28, 46.28, 46.00,
            46.03, 46.41, 46.22, 45.64, 46.21,
        ],
        dtype=np.float64,
    )
    observed = htf._rsi(close, 14)
    assert observed.iloc[:14].isna().all()
    np.testing.assert_allclose(
        observed.iloc[14:21].to_numpy(),
        [70.464135, 66.249619, 66.480942, 69.346853, 66.294713, 57.915021, 62.880718],
        rtol=0.0,
        atol=1e-6,
    )
    flat = htf._rsi(pd.Series(np.ones(20)), 14)
    assert (flat.iloc[14:] == 50.0).all()


