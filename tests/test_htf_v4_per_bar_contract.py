def test_v4_is_one_exact_derived_field_contract() -> None:
    from gx1.features.level_registry_v1 import LEVEL_REGISTRY_MTF_FEATURE_NAMES
    from gx1.features.trendline_registry_v1 import (
        TRENDLINE_REGISTRY_FEATURE_NAMES_V1,
    )

    from gx1.features.smc_v1 import SMC_MTF_FEATURE_NAMES_V1

    expected_width = (
            len(htf.MULTI_TF_V4_GROUP_A_BASE_FEATURES)
            + len(htf.MULTI_TF_V4_VOLUME_FEATURES)
            + len(htf.MULTI_TF_V4_VOLATILITY_SQUEEZE_FEATURES)
        + len(htf.MULTI_TF_V4_CANDLE_PRIMITIVE_FEATURES)
        + len(htf.MULTI_TF_V4_SWING_FEATURES)
        + len(SMC_MTF_FEATURE_NAMES_V1)
        + len(htf.SMC_MTF_GEOMETRY_FEATURE_NAMES_V1)
        + len(EXPECTED_V29_TREND_EVENT_FEATURES)
        + len(EXPECTED_V29_MOMENTUM_EVENT_FEATURES)
        + len(LEVEL_REGISTRY_MTF_FEATURE_NAMES)
        + len(TRENDLINE_REGISTRY_FEATURE_NAMES_V1)
    )
    assert htf.MULTI_TF_FEATURE_COUNT_V4 == expected_width
    assert htf.MULTI_TF_V4_GROUP_A_BASE_FEATURES == (
        EXPECTED_V4_GROUP_A_BASE_FEATURES
    )
    assert (
        htf.MULTI_TF_PER_BAR_FEATURES_V4[
            : len(EXPECTED_V4_GROUP_A_BASE_FEATURES)
        ]
        == EXPECTED_V4_GROUP_A_BASE_FEATURES
    )
    volume_start = len(EXPECTED_V4_GROUP_A_BASE_FEATURES)
    assert htf.MULTI_TF_PER_BAR_FEATURES_V4[
        volume_start : volume_start + len(htf.MULTI_TF_V4_VOLUME_FEATURES)
    ] == htf.MULTI_TF_V4_VOLUME_FEATURES
    assert len(set(htf.MULTI_TF_PER_BAR_FEATURES_V4)) == expected_width
    assert htf.MULTI_TF_V4_TREND_EVENT_FEATURES == (
        EXPECTED_V29_TREND_EVENT_FEATURES
    )
    assert htf.MULTI_TF_V4_MOMENTUM_EVENT_FEATURES == (
        EXPECTED_V29_MOMENTUM_EVENT_FEATURES
    )
    registry_tail = tuple(LEVEL_REGISTRY_MTF_FEATURE_NAMES) + tuple(
        TRENDLINE_REGISTRY_FEATURE_NAMES_V1
    )
    assert htf.MULTI_TF_PER_BAR_FEATURES_V4[-len(registry_tail):] == (
        registry_tail
    )
    event_block = (
        EXPECTED_V29_TREND_EVENT_FEATURES
        + EXPECTED_V29_MOMENTUM_EVENT_FEATURES
    )
    tail_start = -(len(registry_tail) + len(event_block))
    assert (
        htf.MULTI_TF_PER_BAR_FEATURES_V4[tail_start : -len(registry_tail)]
        == event_block
    )


def test_active_technical_outputs_are_raw_owner_formulas() -> None:
    bars = _bars(500, seed=91)
    observed = _compute_v4(bars, timeframe="M5")
    close = bars["close"].astype(np.float64)
    high = bars["high"].astype(np.float64)
    low = bars["low"].astype(np.float64)
    atr = htf._atr(high, low, close, 14)
    atr_positive = atr.where(atr > 0.0)

    expected = {
        "atr_bps_14": atr / close * 1e4,
        "mom_5_atr": (close - close.shift(5)) / atr_positive,
        "mom_20_atr": (close - close.shift(20)) / atr_positive,
        "close_open_atr": (close - bars["open"]) / atr_positive,
    }
    adx, _signed_di = htf._adx14(high, low, close, 14)
    expected["adx14"] = adx
    for name, raw in expected.items():
        np.testing.assert_array_equal(
            observed[name].to_numpy(dtype=np.float32),
            raw.to_numpy(dtype=np.float32),
        )


